def B(**k): return k
def _put(g,x0,y0,block):
    for j,row in enumerate(block.strip('\n').split('\n')):
        for i,c in enumerate(row):
            if c!='_' and 0<=y0+j<40 and 0<=x0+i<40: g[y0+j][x0+i]=c
def at(x,y,block,face=True):
    return lambda g,ox,oy,fx,fy:_put(g,x+(fx if face else 0),y+(fy if face else 0),block)
def onskin(pts):
    def f(g,ox,oy,fx,fy):
        for x,y,c in pts:
            if 0<=y+fy<40 and 0<=x+fx<40 and g[y+fy][x+fx] in 'sSp': g[y+fy][x+fx]=c
    return f
