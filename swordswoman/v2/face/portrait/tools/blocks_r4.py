# ---------- FX helpers: f(g,dx,dy,fx,fy) ----------
def _put(g,x0,y0,block):
    for j,row in enumerate(block.strip('\n').split('\n')):
        for i,c in enumerate(row):
            if c!='_' and 0<=y0+j<40 and 0<=x0+i<40: g[y0+j][x0+i]=c
def at(x,y,block,face=True):
    return lambda g,dx,dy,fx,fy:_put(g,x+(fx if face else 0),y+(fy if face else 0),block)
def onskin(pts):
    def f(g,dx,dy,fx,fy):
        for x,y,c in pts:
            X_,Y_=x+fx,y+fy
            if g[Y_][X_] in 'sSp': g[Y_][X_]=c
    return f
